"use client";

import { FormEvent, useEffect, useState } from "react";
import { AlertTriangle, Check, MessageSquareText, Plus, Sparkles } from "lucide-react";
import { api, can, type PortfolioAnswer, type RagStatus, type AiComparison, type AiFilters, type AiQuestion, type AiReview, type Contract, type User, type Version } from "./api";
import { SectionHeader, Status, amountLabel, dateLabel, dateTimeLabel, errorText } from "./shared";
import { emptyFilters, type Filters } from "./filters";
import { PlaybookResults } from "./playbook";

type PanelProps = { contract: Contract; user: User; onChanged: (contract: Contract) => Promise<void> };

const fieldLabels: Record<string, string> = {
  title: "Title", reference_number: "Reference", vendor_name: "Vendor", project_name: "Project", status: "Status",
  project_start_date: "Start date", project_end_date: "End date", renewal_date: "Renewal date",
  renewal_notice_deadline: "Renewal notice deadline", currency: "Currency", one_time_amount: "One-time amount",
  optional_amount: "Optional amount", payment_terms: "Payment terms", deliverables: "Deliverables", department: "Department", owner: "Owner",
};
const numericFields = new Set(["one_time_amount", "optional_amount"]);
// Status changes go through the lifecycle rules, so the assistant never applies them directly.
const notApplicable = new Set(["status"]);

function Quote({ text }: { text: string | null }) {
  return text ? <blockquote className="ai-quote">“{text}”</blockquote> : null;
}

export function AiPanel({ contract, user, onChanged }: PanelProps) {
  const [status, setStatus] = useState<{ configured: boolean; model: string } | null>(null);
  const [review, setReview] = useState<AiReview | null>(null);
  const [loaded, setLoaded] = useState(false);
  const [busy, setBusy] = useState("");
  const [error, setError] = useState("");
  const [added, setAdded] = useState<Set<number>>(new Set());
  const [applied, setApplied] = useState<Set<string>>(new Set());
  const allowed = can(user, "ai.use");

  useEffect(() => {
    let cancelled = false;
    Promise.all([api.aiStatus(), api.aiReview(contract.id)])
      .then(([s, r]) => { if (!cancelled) { setStatus(s); setReview(r); setLoaded(true); } })
      .catch(err => { if (!cancelled) { setError(errorText(err, "Could not load AI review")); setLoaded(true); } });
    return () => { cancelled = true; };
  }, [contract.id]);

  async function generate() {
    setBusy("review"); setError("");
    try { setReview(await api.runAiReview(contract.id)); setAdded(new Set()); setApplied(new Set()); }
    catch (err) { setError(errorText(err, "The AI review failed")); }
    finally { setBusy(""); }
  }
  async function addObligation(index: number) {
    const item = review!.result.obligations[index];
    setBusy(`ob-${index}`); setError("");
    try {
      await api.createObligation(contract.id, { title: item.title, kind: item.kind, due_date: item.due_date, amount: item.amount, currency: item.currency ?? contract.currency ?? null, notes: item.quote ? `From the contract: “${item.quote}”` : null });
      setAdded(new Set(added).add(index));
    } catch (err) { setError(errorText(err, "Could not add the obligation")); }
    finally { setBusy(""); }
  }
  async function applyField(field: string, value: string) {
    setBusy(`f-${field}`); setError("");
    try {
      const parsed = numericFields.has(field) ? Number(value.replace(/[^0-9.\-]/g, "")) : value;
      await onChanged(await api.update(contract.id, { [field]: parsed } as Partial<Contract>));
      setApplied(new Set(applied).add(field));
    } catch (err) { setError(errorText(err, "Could not update the field")); }
    finally { setBusy(""); }
  }

  const canEdit = can(user, "contract.edit") && !contract.pending_approval_id;
  const r = review?.result;
  return <div className="wf-panel ai-panel">
    {status && !status.configured && <p className="wf-hint warn">AI features are off: add the Azure OpenAI settings to <code>.env</code> and restart the API.</p>}
    {error && <p className="form-error">{error}</p>}

    <section className="wf-card">
      <header className="wf-card-head"><div><h3><Sparkles size={16}/> AI review</h3>
        <small>{review ? `Generated by ${review.created_by} · ${dateTimeLabel(review.created_at)} · document v${review.document_version}` : "Summary, key terms, risky clauses, obligations and data checks."}</small></div>
        {allowed && <button className={review ? "secondary-button" : "primary-button"} disabled={!!busy || status?.configured === false} onClick={generate}>{busy === "review" ? "Reviewing… (up to a minute)" : review ? "Run again" : "Run AI review"}</button>}</header>
      {review?.stale && <p className="wf-hint warn">A newer document version exists. Run the review again to check it.</p>}
      {loaded && !review && !allowed && <p className="wf-hint">No AI review yet. Ask a colleague with edit access to run one.</p>}
      {r && <>
        <p className="ai-summary">{r.summary}</p>
        {r.key_terms.length > 0 && <><h4 className="wf-subhead">Key terms</h4><dl className="ai-terms">{r.key_terms.map((t, i) => <div key={i}><dt>{t.label}</dt><dd>{t.value}</dd></div>)}</dl></>}

        <h4 className="wf-subhead">Risks ({r.risks.length})</h4>
        {r.risks.length ? <ul className="ai-risks">{r.risks.map((risk, i) => <li key={i} className={risk.severity}>
          <span className={`ai-sev ${risk.severity}`}>{risk.severity}</span>
          <div><strong>{risk.category}: {risk.finding}</strong><Quote text={risk.quote} /><p>→ {risk.recommendation}</p></div>
        </li>)}</ul> : <p className="wf-hint">No risks flagged.</p>}

        {r.playbook && r.playbook.length > 0 && <PlaybookResults checks={r.playbook} />}

        {r.missing_clauses.length > 0 && <><h4 className="wf-subhead">Possibly missing</h4><div className="wf-chain">{r.missing_clauses.map(c => <span key={c} className="wf-chip ai-missing"><AlertTriangle size={13}/> {c}</span>)}</div></>}

        {r.field_mismatches.length > 0 && <><h4 className="wf-subhead">Record vs document</h4><ul className="wf-list">{r.field_mismatches.map(m => <li key={m.field}>
          <div><strong>{fieldLabels[m.field] ?? m.field}</strong><small>Record: {m.record_value ?? "empty"} · Document: {m.document_value}</small><Quote text={m.quote} /></div>
          {canEdit && !notApplicable.has(m.field) && (applied.has(m.field) ? <span className="wf-current"><Check size={12}/> Updated</span> :
            <button className="secondary-button" disabled={!!busy} onClick={() => void applyField(m.field, m.document_value)}>Use document value</button>)}
        </li>)}</ul></>}

        <h4 className="wf-subhead">Suggested obligations ({r.obligations.length})</h4>
        {r.obligations.length ? <ul className="wf-list">{r.obligations.map((o, i) => <li key={i}>
          <span className="wf-badge">{o.kind}</span>
          <div><strong>{o.title}</strong><small>{o.due_date ? `Due ${dateLabel(o.due_date)}` : "No exact date"}{o.amount != null ? ` · ${amountLabel(o.currency, o.amount)}` : ""}</small><Quote text={o.quote} /></div>
          {can(user, "obligation.manage") && (added.has(i) ? <span className="wf-current"><Check size={12}/> Added</span> :
            <button className="secondary-button" disabled={!!busy} onClick={() => void addObligation(i)}><Plus size={14}/> Add</button>)}
        </li>)}</ul> : <p className="wf-hint">No obligations found.</p>}
        <p className="wf-hint ai-disclaimer">AI output can be wrong. Check quotes against the document before relying on them.</p>
      </>}
    </section>

    <AskPanel contract={contract} allowed={allowed && status?.configured !== false} />
    <ComparePanel contract={contract} allowed={allowed && status?.configured !== false} />
  </div>;
}

function AskPanel({ contract, allowed }: { contract: Contract; allowed: boolean }) {
  const [history, setHistory] = useState<AiQuestion[]>([]);
  const [question, setQuestion] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  useEffect(() => {
    let cancelled = false;
    api.aiQuestions(contract.id).then(h => { if (!cancelled) setHistory(h); }).catch(() => undefined);
    return () => { cancelled = true; };
  }, [contract.id]);
  async function ask(event: FormEvent) {
    event.preventDefault(); setBusy(true); setError("");
    try { const answer = await api.askAi(contract.id, question); setHistory([answer, ...history]); setQuestion(""); }
    catch (err) { setError(errorText(err, "Could not get an answer")); }
    finally { setBusy(false); }
  }
  return <section className="wf-card">
    <h3><MessageSquareText size={16}/> Ask about this contract</h3>
    {allowed && <form className="ai-ask" onSubmit={ask}>
      <input value={question} maxLength={1000} onChange={e => setQuestion(e.target.value)} placeholder="e.g. What notice do we need to give to terminate?" aria-label="Question" />
      <button className="primary-button" disabled={busy || !question.trim()}>{busy ? "Thinking…" : "Ask"}</button>
    </form>}
    {error && <p className="form-error">{error}</p>}
    {!history.length && <p className="wf-hint">Answers come only from this contract’s document and record, with quotes.</p>}
    <ul className="ai-answers">{history.map(item => <li key={item.id}>
      <p className="ai-q">{item.question}<small> — {item.asked_by}, {dateTimeLabel(item.created_at)}</small></p>
      <p className={item.answer.found ? "ai-a" : "ai-a notfound"}>{item.answer.found ? "" : "Not in the contract: "}{item.answer.answer}</p>
      {item.answer.citations.map((c, i) => <Quote key={i} text={c.quote} />)}
    </li>)}</ul>
  </section>;
}

function ComparePanel({ contract, allowed }: { contract: Contract; allowed: boolean }) {
  const [versions, setVersions] = useState<Version[]>([]);
  const [from, setFrom] = useState<number | "">("");
  const [to, setTo] = useState<number | "">("");
  const [result, setResult] = useState<AiComparison | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  useEffect(() => {
    let cancelled = false;
    api.versions(contract.id).then(v => {
      if (cancelled) return;
      setVersions(v);
      if (v.length >= 2) { setTo(v[0].version); setFrom(v[1].version); }
    }).catch(() => undefined);
    return () => { cancelled = true; };
  }, [contract.id, contract.document_version]);
  if (versions.length < 2) return null;
  async function run() {
    if (from === "" || to === "") return;
    setBusy(true); setError("");
    try { setResult(await api.aiCompare(contract.id, from, to)); } catch (err) { setError(errorText(err, "Comparison failed")); } finally { setBusy(false); }
  }
  return <section className="wf-card">
    <h3><Sparkles size={16}/> Compare versions</h3>
    <div className="ai-compare-bar">
      <select aria-label="Older version" value={from} onChange={e => setFrom(Number(e.target.value))}>{versions.map(v => <option key={v.id} value={v.version}>v{v.version} · {v.file_name}</option>)}</select>
      <span>→</span>
      <select aria-label="Newer version" value={to} onChange={e => setTo(Number(e.target.value))}>{versions.map(v => <option key={v.id} value={v.version}>v{v.version} · {v.file_name}</option>)}</select>
      {allowed && <button className="primary-button" disabled={busy || from === to} onClick={run}>{busy ? "Comparing…" : "Compare"}</button>}
    </div>
    {error && <p className="form-error">{error}</p>}
    {result && <>
      <p className="ai-summary">{result.summary}</p>
      <ul className="wf-list">{result.changes.map((c, i) => <li key={i}>
        <span className={`ai-impact ${c.impact}`}>{c.impact}</span>
        <div><strong>{c.topic}</strong>{c.before && <small><del>{c.before}</del></small>}{c.after && <small><ins>{c.after}</ins></small>}<p>{c.note}</p></div>
      </li>)}</ul>
    </>}
  </section>;
}

/** Natural-language search box for the contracts page. */
export function AiSearch({ onApply }: { onApply: (filters: Filters, search: string, explanation: string) => void }) {
  const [query, setQuery] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  async function submit(event: FormEvent) {
    event.preventDefault(); setBusy(true); setError("");
    try {
      const f: AiFilters = await api.aiSearch(query);
      onApply({
        ...emptyFilters, status: f.status ?? "", vendor: f.vendor ?? "", department: f.department ?? "", owner: f.owner ?? "",
        tag: f.tag ?? "", currency: f.currency ?? "", minValue: f.min_value != null ? String(f.min_value) : "",
        maxValue: f.max_value != null ? String(f.max_value) : "", endFrom: f.end_from ?? "", endTo: f.end_to ?? "",
      }, f.search ?? "", f.explanation);
    } catch (err) { setError(errorText(err, "AI search failed")); }
    finally { setBusy(false); }
  }
  return <form className="ai-search" onSubmit={submit}>
    <Sparkles size={17}/>
    <input value={query} onChange={e => setQuery(e.target.value)} maxLength={500} placeholder="Ask in plain words, e.g. “Adobe contracts over 100k ending next quarter”" aria-label="AI search" />
    <button className="secondary-button" disabled={busy || !query.trim()}>{busy ? "Working…" : "Find"}</button>
    {error && <p className="form-error">{error}</p>}
  </form>;
}

const portfolioExamples = [
  "Which contracts end in the next 90 days, and what is their total value per currency?",
  "Which vendors have contracts with high AI risks?",
  "What payments are due this quarter?",
  "Which contracts are waiting for finance approval?",
];

const documentExamples = [
  "Which contracts cap the supplier's liability, and at what level?",
  "Which contracts allow termination for convenience, and with how much notice?",
  "Where do we have data protection or confidentiality obligations?",
];

/** Questions across the whole portfolio: from records (structured) or from document text (LightRAG). */
export function PortfolioView({ onOpen }: { onOpen: (contractId: number) => void }) {
  const [history, setHistory] = useState<PortfolioAnswer[]>([]);
  const [question, setQuestion] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  const [configured, setConfigured] = useState(true);
  const [rag, setRag] = useState<RagStatus | null>(null);
  const [source, setSource] = useState<"records" | "documents">("records");
  const [ragTick, setRagTick] = useState(0);
  useEffect(() => {
    let cancelled = false;
    api.aiStatus().then(s => { if (!cancelled) setConfigured(s.configured); }).catch(() => undefined);
    api.portfolioHistory().then(h => { if (!cancelled) setHistory(h); }).catch(err => { if (!cancelled) setError(errorText(err, "Could not load history")); });
    return () => { cancelled = true; };
  }, []);
  useEffect(() => {
    let cancelled = false;
    api.ragStatus().then(s => { if (!cancelled) setRag(s); }).catch(() => undefined);
    return () => { cancelled = true; };
  }, [ragTick]);
  const pending = rag ? (rag.counts.Queued ?? 0) + (rag.counts.Indexing ?? 0) : 0;
  useEffect(() => {
    if (!pending) return;
    const timer = window.setTimeout(() => setRagTick(t => t + 1), 3000);
    return () => window.clearTimeout(timer);
  }, [pending, ragTick]);

  async function ask(text: string) {
    setBusy(true); setError("");
    try { const item = source === "documents" ? await api.askDocuments(text) : await api.askPortfolio(text); setHistory([item, ...history]); setQuestion(""); }
    catch (err) { setError(errorText(err, "Could not get an answer")); }
    finally { setBusy(false); }
  }
  async function reindex() {
    setError("");
    try { await api.ragReindex(); setRagTick(t => t + 1); } catch (err) { setError(errorText(err, "Could not rebuild the index")); }
  }
  const examples = source === "documents" ? documentExamples : portfolioExamples;
  return <>
    <SectionHeader eyebrow="AI ASSISTANT" title="Ask about your portfolio" copy={source === "documents"
      ? "Answers come from the text of the contract documents, searched with a knowledge graph (LightRAG). Every contract quoted is linked."
      : "Answers come from contract records, obligations, approvals and the latest AI reviews — every contract it relies on is linked."} />
    {!configured && <p className="wf-hint warn">AI features are off: add the Azure OpenAI settings to <code>.env</code> and restart the API.</p>}
    <section className="panel portfolio-ask">
      {rag?.enabled && <div className="portfolio-source" role="radiogroup" aria-label="Answer from">
        <button role="radio" aria-checked={source === "records"} className={source === "records" ? "active" : ""} onClick={() => setSource("records")}>Contract records</button>
        <button role="radio" aria-checked={source === "documents"} className={source === "documents" ? "active" : ""} onClick={() => setSource("documents")}>Document text</button>
      </div>}
      <form className="ai-ask" onSubmit={e => { e.preventDefault(); void ask(question); }}>
        <input value={question} maxLength={1000} onChange={e => setQuestion(e.target.value)} placeholder={source === "documents" ? "e.g. Which contracts have uncapped liability?" : "e.g. Which contracts renew next quarter and who owns them?"} aria-label="Portfolio question" />
        <button className="primary-button" disabled={busy || !question.trim() || !configured}>{busy ? "Thinking…" : "Ask"}</button>
      </form>
      <div className="portfolio-examples">{examples.map(example => <button key={example} className="wf-chip" disabled={busy || !configured} onClick={() => void ask(example)}>{example}</button>)}</div>
      {rag?.enabled && source === "documents" && <div className="rag-status">
        <span>{rag.counts.Indexed ?? 0} of {rag.documents} document{rag.documents === 1 ? "" : "s"} indexed{pending ? ` · ${pending} in progress…` : ""}{rag.counts.Failed ? ` · ${rag.counts.Failed} could not be read` : ""}</span>
        {rag.can_reindex && <button className="link-button" onClick={() => void reindex()}>Rebuild index</button>}
        {rag.failed.length > 0 && <details><summary>Documents that could not be indexed</summary><ul>{rag.failed.map(f => <li key={f.contract_id}><button className="link-button" onClick={() => onOpen(f.contract_id)}>{f.title ?? `Contract #${f.contract_id}`}</button> — {f.error}</li>)}</ul></details>}
      </div>}
      {error && <p className="form-error">{error}</p>}
    </section>
    <ul className="ai-answers portfolio-answers">{history.map(item => <li key={item.id} className="panel">
      <p className="ai-q"><span className={`source-badge ${item.source}`}>{item.source === "documents" ? "Documents" : "Records"}</span>{item.question}<small> — {dateTimeLabel(item.created_at)}</small></p>
      <p className={item.answer.found ? "ai-a" : "ai-a notfound"}>{item.answer.found ? "" : "Not answerable from the data: "}{item.answer.answer}</p>
      {item.answer.contracts.length > 0 && <div className="portfolio-refs">{item.answer.contracts.map(c => <button key={c.id} onClick={() => onOpen(c.id)}>
        <div><strong>{c.title}</strong><small>{c.vendor_name ?? "Vendor not identified"} · {item.source === "documents" ? `“${c.reason}”` : c.reason}</small></div><Status value={c.status} />
      </button>)}</div>}
    </li>)}</ul>
    {history.length > 0 && <p className="wf-hint ai-disclaimer">AI output can be wrong. Open the linked contracts to check before acting.</p>}
  </>;
}
